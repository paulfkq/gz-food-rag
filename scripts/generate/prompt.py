"""Prompt 构造：这是"防幻觉"的主战场。

RAG 的答案质量 = 检索证据质量 × prompt 约束力 × 模型能力。
检索这步已经把硬约束 100% 保证好了，生成这步的唯一任务就是：
【忠实于证据】—— 只用给它的材料回答，不给的就承认不知道，绝不自由发挥。

设计要点（新手要理解每一条的用意）：
    1. system 里把"只能用证据、禁止编造、必须带引用"写成硬规则。
    2. 每条证据编号 [1][2]...，要求答案里用 [编号] 引用 —— 这样引用可校验。
    3. 显式告诉模型"价格/评分/过敏原只能照抄证据原文" —— 数字是幻觉重灾区。
    4. 用户 prompt 里附上原始 query 和槽位摘要，让模型知道"为什么推荐这些店"
       （比如用户要求了不要花生，答案里可以点出这家店不含花生）。
    5. temperature=0 在 LLMClient 里设，进一步压低随机性。
"""
from __future__ import annotations

from retrieve.verify import FinalHit

SYSTEM_PROMPT = """你是一个广州美食推荐助手。你的任务是【只根据提供给你的餐厅资料】回答用户问题。

## 铁律（违反任何一条都是错误）
1. 只能使用下面【候选餐厅资料】里的信息。资料里没有的店、菜、价格、评分、设施，绝对不能编造。
2. 每提到一家店，必须在店名后标注它的引用编号，格式如：西华路明记肠粉[1]。引用编号只能来自资料中给出的编号。
3. 价格、评分、过敏原、地铁步行时间等【数字和事实必须照抄资料原文】，不能估算、不能改写、不能四舍五入。
4. 如果资料里没有能满足用户所有要求的店，就如实说"根据现有资料，没有完全符合条件的店"，并说明哪条要求难以满足；不要硬凑。
5. 不要输出资料之外的主观臆断（如"这家店全广州最好吃"这类没有依据的话）。

## 回答结构
- 先一句话总述（如"为你找到 N 家符合要求的店"）。
- 然后按推荐顺序列出每家店，每家 2~4 句：店名[编号]、为什么符合用户要求（结合用户提到的条件）、关键事实（人均/评分/位置/过敏原等照抄资料）。
- 最后可以给一句简短的实用提醒（只在资料支持范围内）。
- 语气自然、简洁，像一个熟悉广州的本地朋友在推荐。"""


def build_user_prompt(query: str, slots_summary: str, hits: list[FinalHit]) -> str:
    parts = [f"## 用户的原始问题\n{query}\n"]
    if slots_summary:
        parts.append(f"## 已解析出的筛选条件（供你理解用户意图，不必复述）\n{slots_summary}\n")
    parts.append("## 候选餐厅资料（这是你唯一可以使用的信息来源）")
    for i, h in enumerate(hits, 1):
        parts.append(f"\n--- [{i}] {h.shop_name}（ID {h.shop_id}）---")
        parts.append(h.parent_text.strip())
        if h.matched_soft:
            parts.append(f"（检索命中偏好：{'、'.join(h.matched_soft)}）")
    parts.append("\n## 现在请按铁律回答用户的问题：")
    return "\n".join(parts)
